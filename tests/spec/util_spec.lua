local H, WoW = ...
local describe, it = H.describe, H.it

describe('Util', function()
  local ctl = WoW.start({ login = false })
  local Util = ctl.ns.Util

  it('splits keeping empty fields', function()
    local parts = Util.split('a||c', '|')
    H.eq(#parts, 3)
    H.eq(parts[2], '')
  end)

  it('formats dates and ordinals', function()
    H.eq(Util.formatDate('26-11-12'), 'November 12, 2026')
    H.eq(Util.formatDate('26-11-12', true), 'Nov 12, 2026')
    H.eq(Util.formatDate('nope'), 'an unknown date')
    H.eq(Util.ordinal(1), '1st')
    H.eq(Util.ordinal(12), '12th')
    H.eq(Util.ordinal(22), '22nd')
    H.eq(Util.ordinal(113), '113th')
  end)

  it('computes whole days, across DST', function()
    H.eq(Util.daysBetween('26-03-01', '26-04-01'), 31)
    H.eq(Util.daysBetween('26-11-01', '26-11-12'), 11)
    H.eq(Util.daysBetween('26-11-12', '26-11-01'), 11)
    H.eq(Util.daysAgo(Util.today()), 0)
    H.eq(Util.relativeDate('26-11-11'), 'yesterday')
    H.eq(Util.relativeDate('26-11-02'), '10 days ago')
  end)

  it('turns localized loot strings into safe patterns', function()
    local pattern = Util.formatToPattern('You receive loot: %sx%d.')
    local link, count = string.match('You receive loot: |cff9d9d9d|Hitem:2589::|h[Linen Cloth]|h|rx3.', pattern)
    H.eq(count, '3')
    H.eq(Util.itemNameFromLink(link), 'Linen Cloth')
    H.eq(Util.itemIdFromLink(link), 2589)
    -- positional and magic characters (e.g. German / French style strings)
    local p2 = Util.formatToPattern('Beute (%1$s) erhalten.')
    H.eq(string.match('Beute (X-Y) erhalten.', p2), 'X-Y')
  end)
end)

describe('Safe', function()
  local ctl = WoW.start({ login = false })
  local Safe = ctl.ns.Safe

  it('detects secret values and scrubs them', function()
    H.truthy(Safe.isSecret(ctl.SECRET))
    H.falsy(Safe.isSecret('x'))
    H.eq(Safe.value(ctl.SECRET), nil)
    H.eq(Safe.str(ctl.SECRET), nil)
    H.eq(Safe.str(''), nil)
    local a, b = Safe.call(function() return ctl.SECRET, 'ok' end)
    H.eq(a, nil)
    H.eq(b, 'ok')
  end)

  it('swallows API errors and missing APIs', function()
    H.eq(Safe.call(function() error('boom') end), nil)
    H.eq(Safe.api('DoesNotExist'), nil)
    H.eq(Safe.api('C_Item.Missing'), nil)
    H.falsy(Safe.has('DoesNotExist'))
    H.truthy(Safe.has('C_Item.GetItemCount'))
  end)

  it('classifies GUIDs', function()
    H.truthy(Safe.isNpcGuid('Creature-0-1-2-3-4-5'))
    H.truthy(Safe.isNpcGuid('Vehicle-0-1-2-3-4-5'))
    H.falsy(Safe.isNpcGuid('GameObject-0-1-2'))
    H.truthy(Safe.isPlayerGuid('Player-1-0001'))
  end)
end)
